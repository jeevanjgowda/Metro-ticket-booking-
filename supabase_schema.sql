-- Supabase SQL Editor script for Metro Ticket Booking
-- Copy and run this script inside Supabase SQL Editor (New Query)

create table public.bookings (
  id bigint generated by default as identity primary key,
  name text not null,
  tickets integer not null,
  line text not null,
  route text not null,
  ticket_type text not null,
  total_fare numeric not null,
  created_at timestamp with time zone default now()
);

-- Note: RLS (Row Level Security) can be disabled or configured for public inserts & selects during development.
